import { intersection, isIncludeAllChildren, isString } from '@pureadmin/utils';
import { router } from '../index';

/** 判断两个数组彼此是否存在相同值 */
function isOneOfArray(a: Array<string>, b: Array<string>) {
  return Array.isArray(a) && Array.isArray(b) ? intersection(a, b).length > 0 : false;
}

/** 获取当前页面按钮级别的权限 */
function getAuths(): Array<string> {
  return router.currentRoute.value.meta.auths as Array<string>;
}

/** 是否有按钮级别的权限（根据路由`meta`中的`auths`字段进行判断）*/
function hasAuth(value: string | Array<string>): boolean {
  if (!value) return false;
  /** 从当前路由的`meta`字段里获取按钮级别的所有自定义`code`值 */
  const metaAuths = getAuths();
  if (!metaAuths) return false;
  return isString(value) ? metaAuths.includes(value) : isIncludeAllChildren(value, metaAuths);
}

export { getAuths, hasAuth, isOneOfArray };
